plugins {
    `kotlin-dsl`
    jacoco
}

gradlePlugin {
    plugins {
        create("buildLogicTestFixture") {
            id = "cloudsim-benchmark.buildlogic-test-fixture"
            implementationClass = "buildlogic.BuildLogicTestFixturePlugin"
        }
    }
}

repositories {
    gradlePluginPortal()
    mavenCentral()
}

val testKitJacocoAgent by configurations.creating {
    isCanBeConsumed = false
    isCanBeResolved = true
}

kotlin {
    jvmToolchain(25)
}

tasks.withType<org.jetbrains.kotlin.gradle.tasks.KotlinCompile>().configureEach {
    compilerOptions {
        jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.fromTarget("25"))
    }
}

dependencies {
    testImplementation(kotlin("test"))
    testImplementation("org.junit.jupiter:junit-jupiter:6.1.0")
    testImplementation(gradleTestKit())
    testKitJacocoAgent("org.jacoco:org.jacoco.agent:${jacoco.toolVersion}:runtime")
}

val testKitJacocoDirectory = layout.buildDirectory.dir("jacoco/testkit")
val testKitJacocoPath = testKitJacocoDirectory.get().asFile.absolutePath
val jacocoAgentPath = testKitJacocoAgent.singleFile.absolutePath

tasks.withType<Test>().configureEach {
    useJUnitPlatform()
    outputs.doNotCacheIf("JaCoCo execution data must be generated by the current test JVM") { true }
    systemProperty("buildlogic.testkit.jacocoAgent", jacocoAgentPath)
    systemProperty("buildlogic.testkit.jacocoDirectory", testKitJacocoPath)
}

tasks.named<Test>("test") {
    finalizedBy(tasks.named("jacocoTestReport"))
}

fun registerTestShard(
    name: String,
    includes: List<String>,
    excludes: List<String> = emptyList(),
) =
    tasks.register<Test>(name) {
        group = "verification"
        description = "Runs the $name buildSrc test shard"
        testClassesDirs = sourceSets["test"].output.classesDirs
        classpath = sourceSets["test"].runtimeClasspath
        filter {
            includes.forEach(::includeTestsMatching)
            excludes.forEach(::excludeTestsMatching)
            isFailOnNoMatchingTests = true
        }
    }

val unitTest =
    registerTestShard(
        name = "unitTest",
        includes = listOf("buildlogic.*"),
        excludes = listOf("buildlogic.*FunctionalTest"),
    )
val cloudSimPlusFunctionalTest =
    registerTestShard(
        name = "cloudSimPlusFunctionalTest",
        includes =
            listOf(
                "buildlogic.CloudSimPlus*FunctionalTest",
                "buildlogic.UpdateCloudSimPlusLockTaskFunctionalTest",
            ),
    )
val verificationFunctionalTest =
    registerTestShard(
        name = "verificationFunctionalTest",
        includes =
            listOf(
                "buildlogic.BuildWarningAuditTaskFunctionalTest",
                "buildlogic.JUnitVerificationTaskFunctionalTest",
                "buildlogic.LicensePolicyTaskFunctionalTest",
                "buildlogic.VerifyGitHubActionsPolicyTaskFunctionalTest",
            ),
    )
val containerFunctionalTest =
    registerTestShard(
        name = "containerFunctionalTest",
        includes =
            listOf(
                "buildlogic.ContainerImageSmokeTaskFunctionalTest",
                "buildlogic.ContainerImageContextTaskFunctionalTest",
                "buildlogic.CliEndToEndSmokeTaskFunctionalTest",
        ),
    )
val testShards =
    listOf(
        unitTest,
        cloudSimPlusFunctionalTest,
        verificationFunctionalTest,
        containerFunctionalTest,
    )

tasks.named<JacocoReport>("jacocoTestReport") {
    dependsOn(tasks.named("test"))
    mustRunAfter(testShards)
    executionData(fileTree(layout.buildDirectory.dir("jacoco")) { include("**/*.exec") })
    reports {
        xml.required.set(true)
        html.required.set(true)
    }
}

tasks.named<JacocoCoverageVerification>("jacocoTestCoverageVerification") {
    dependsOn(tasks.named("test"))
    mustRunAfter(testShards)
    executionData(fileTree(layout.buildDirectory.dir("jacoco")) { include("**/*.exec") })
    violationRules {
        rule {
            limit {
                counter = "LINE"
                value = "COVEREDRATIO"
                minimum = "0.65".toBigDecimal()
            }
            limit {
                counter = "BRANCH"
                value = "COVEREDRATIO"
                minimum = "0.50".toBigDecimal()
            }
        }
        listOf(
            "buildlogic.CloudSimPlusGitStateFiles",
            "buildlogic.CloudSimPlusGitClient",
            "buildlogic.CloudSimPlusSourcePreparer",
        ).forEach { className ->
            rule {
                element = "CLASS"
                includes = listOf(className)
                limit {
                    counter = "LINE"
                    value = "COVEREDRATIO"
                    minimum = "0.75".toBigDecimal()
                }
                limit {
                    counter = "BRANCH"
                    value = "COVEREDRATIO"
                    minimum = "0.60".toBigDecimal()
                }
            }
        }
        rule {
            element = "CLASS"
            includes = listOf("buildlogic.VerifyCloudSimPlusSourceBuildTask")
            limit {
                counter = "LINE"
                value = "COVEREDRATIO"
                minimum = "0.75".toBigDecimal()
            }
            limit {
                counter = "BRANCH"
                value = "COVEREDRATIO"
                minimum = "0.60".toBigDecimal()
            }
        }
        rule {
            element = "CLASS"
            includes = listOf("buildlogic.VerifyContainerImageContextTask")
            limit {
                counter = "LINE"
                value = "COVEREDRATIO"
                minimum = "0.80".toBigDecimal()
            }
            limit {
                counter = "BRANCH"
                value = "COVEREDRATIO"
                minimum = "0.70".toBigDecimal()
            }
        }
    }
}

tasks.named("check") {
    dependsOn("jacocoTestReport", "jacocoTestCoverageVerification")
}
